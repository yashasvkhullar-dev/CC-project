import numpy as np
import pandas as pd

def select_compute_tier(cpu):
    if cpu < CPU_THRESHOLDS['small_max']:
        return 'Small'
    elif cpu < CPU_THRESHOLDS['medium_max']:
        return 'Medium'
    else:
        return 'Large'


def estimate_interval_cost(cpu, duration_hours=INTERVAL_HOURS):
    tier = select_compute_tier(cpu)
    hourly_rate = CLOUD_PRICING[tier]
    cost = hourly_rate * duration_hours

    return tier, cost


